"""Turn validated patches into pull requests.

For each validated patch:
  1. git checkout -b codeaudit/<rule>-<id>       (from the current branch)
  2. git apply --index patches/<id>.diff
  3. git commit  (message = analyst summary + validator checks)
  4. back to the original branch
With --push and a GITHUB_TOKEN:
  5. git push -u origin <branch>
  6. POST https://api.github.com/repos/<owner>/<repo>/pulls

--sandbox copies the audited folder into audit_out/pr_sandbox, makes it a git repo and creates the
branches there: shows the whole PR flow offline without touching the original project.
"""
from __future__ import annotations
import json
import os
import re
import shutil
import subprocess
import urllib.request
from pathlib import Path

from .agents.validator import COPY_IGNORE


class PRError(RuntimeError):
    pass


def git(repo: str, *args: str, check: bool = True) -> str:
    r = subprocess.run(["git", "-C", repo, *args], capture_output=True, text=True)
    if check and r.returncode != 0:
        raise PRError(f"git {' '.join(args)} failed: {(r.stderr or r.stdout).strip()[:300]}")
    return r.stdout.strip()


def _identity(repo: str) -> list[str]:
    has = git(repo, "config", "user.email", check=False)
    return [] if has else ["-c", "user.name=CodeAudit", "-c", "user.email=codeaudit@localhost"]


def is_git_repo(path: str) -> bool:
    return subprocess.run(["git", "-C", path, "rev-parse", "--is-inside-work-tree"],
                          capture_output=True, text=True).stdout.strip() == "true"


def is_git_root(path: str) -> bool:
    """True only when the folder is the top of its own repository, not a folder inside a bigger one
    (e.g. a home directory that is itself a git repo)."""
    top = subprocess.run(["git", "-C", path, "rev-parse", "--show-toplevel"],
                         capture_output=True, text=True).stdout.strip()
    return bool(top) and Path(top).resolve() == Path(path).resolve()


def prepare_sandbox(repo: str, dest: str) -> str:
    d = Path(dest)
    if d.exists():
        shutil.rmtree(d)
    shutil.copytree(repo, d, ignore=COPY_IGNORE)
    git(str(d), "init", "-q", "-b", "main")
    git(str(d), "add", "-A")
    git(str(d), *_identity(str(d)), "commit", "-q", "-m", "baseline before CodeAudit")
    return str(d)


def pr_text(result: dict) -> tuple[str, str]:
    f, a = result["finding"], result.get("analysis", {})
    v = result["refactor"]["validation"]
    title = f"[CodeAudit] {f['rule'].replace('_', ' ').lower()}: {f['message'][:70]}"
    checks = "\n".join(f"- [{'x' if c['passed'] else ' '}] {c['name']} {c['detail']}" for c in v["checks"])
    plan = "\n".join(f"- {x}" for x in a.get("fix_plan", []))
    body = (f"**Finding {f['id']}** `{f['rule']}`{' (' + f['cwe'] + ')' if f.get('cwe') else ''} in "
            f"`{f['file']}:{f['start_line']}`\n\n{f['message']}\n\n"
            f"**Why it matters:** {a.get('summary', '')} {a.get('impact', '')}\n\n"
            f"**Root cause:** {a.get('root_cause', '')}\n\n**Plan:**\n{plan}\n\n"
            f"**Change:** {v.get('description', '')} (produced by {result['refactor'].get('by')})\n\n"
            f"**Validator:**\n{checks}\n\n_Generated by CodeAudit — please review before merging._")
    return title, body


def create_branch_commit(repo: str, branch: str, patch_file: str, message: str) -> str:
    if not is_git_repo(repo):
        raise PRError(f"{repo} is not a git repository (use --sandbox to try the flow on a copy)")
    if git(repo, "status", "--porcelain", "--untracked-files=no"):
        raise PRError("working tree has uncommitted changes; commit or stash them first")
    base = git(repo, "rev-parse", "--abbrev-ref", "HEAD")
    if git(repo, "branch", "--list", branch):
        git(repo, "branch", "-D", branch)
    git(repo, "checkout", "-q", "-b", branch)
    try:
        prefix = git(repo, "rev-parse", "--show-prefix")              # audited folder inside a bigger repo
        args = ["apply", "--index"] + ([f"--directory={prefix.rstrip('/')}"] if prefix else []) + [patch_file]
        git(repo, *args)
        git(repo, *_identity(repo), "commit", "-q", "-m", message)
        sha = git(repo, "rev-parse", "--short", "HEAD")
    finally:
        git(repo, "checkout", "-q", base, check=False)
    return sha


def _github_slug(repo: str) -> tuple[str, str] | None:
    url = git(repo, "remote", "get-url", "origin", check=False)
    m = re.search(r"github\.com[:/]([^/]+)/([^/]+?)(\.git)?$", url)
    return (m.group(1), m.group(2)) if m else None


def push_and_open_pr(repo: str, branch: str, title: str, body: str, base: str | None = None) -> str:
    token = os.getenv("GITHUB_TOKEN") or os.getenv("GH_TOKEN")
    if not token:
        raise PRError("GITHUB_TOKEN is not set; branch was created locally only")
    slug = _github_slug(repo)
    if not slug:
        raise PRError("origin is not a GitHub remote")
    git(repo, "push", "-q", "-u", "origin", branch)
    base = base or git(repo, "rev-parse", "--abbrev-ref", "HEAD")
    req = urllib.request.Request(
        f"https://api.github.com/repos/{slug[0]}/{slug[1]}/pulls", method="POST",
        data=json.dumps({"title": title, "head": branch, "base": base, "body": body}).encode(),
        headers={"authorization": f"Bearer {token}", "accept": "application/vnd.github+json",
                 "x-github-api-version": "2022-11-28", "content-type": "application/json"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read())["html_url"]


def export_prs(audit_dir: str, repo: str | None = None, push: bool = False, sandbox: bool = False,
               only: list[str] | None = None, log=print) -> list[dict]:
    audit = Path(audit_dir)
    data = json.loads((audit / "results.json").read_text(encoding="utf-8"))
    repo = repo or data["summary"]["repo"]
    if sandbox:
        repo = prepare_sandbox(repo, str(audit / "pr_sandbox"))
        log(f"sandbox git repo: {repo}")
    out = []
    for r in data["results"]:
        f = r["finding"]
        if not r.get("refactor", {}).get("ok") or (only and f["id"] not in only):
            continue
        patch = (audit / "patches" / f"{f['id']}.diff").resolve()
        branch = f"codeaudit/{f['rule'].lower().replace('_', '-')}-{f['id'].lower()}"
        title, body = pr_text(r)
        row = {"finding": f["id"], "branch": branch, "title": title}
        try:
            row["commit"] = create_branch_commit(repo, branch, str(patch), f"{title}\n\n{body}")
            log(f"{f['id']}: branch {branch} @ {row['commit']}")
            if push:
                row["pr_url"] = push_and_open_pr(repo, branch, title, body)
                log(f"{f['id']}: pull request {row['pr_url']}")
        except (PRError, OSError) as e:
            row["error"] = str(e)
            log(f"{f['id']}: {e}")
        out.append(row)
    (audit / "prs.json").write_text(json.dumps({"repo": repo, "prs": out}, indent=1), encoding="utf-8")
    return out
